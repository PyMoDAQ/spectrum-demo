"""Build ontology/external_excerpt.ttl: the few QUDT and CHMO terms the demo uses.

The demo must run offline, so instead of downloading QUDT (4 MB) and CHMO (6 MB)
at run time, we keep a small excerpt with only the triples we need
(labels, definitions, unit conversion multipliers, symbols).

Usage (only needed to refresh the excerpt):

    python scripts/build_external_excerpt.py QUANTITY_KINDS.ttl UNITS.ttl chmo.owl

Sources used on 2026-11-14:
  https://raw.githubusercontent.com/qudt/qudt-public-repo/main/src/main/rdf/vocab/quantitykinds/VOCAB_QUDT-QUANTITY-KINDS-ALL.ttl
  https://raw.githubusercontent.com/qudt/qudt-public-repo/main/src/main/rdf/vocab/unit/VOCAB_QUDT-UNITS-ALL.ttl
  https://raw.githubusercontent.com/rsc-ontologies/rsc-cmo/master/chmo.owl  (release 2026-10-26)
QUDT and CHMO are both CC BY 4.0.
"""
import sys
from pathlib import Path

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCTERMS, RDF, RDFS, SKOS

QUDT = Namespace("http://qudt.org/schema/qudt/")
QK = Namespace("http://qudt.org/vocab/quantitykind/")
UNIT = Namespace("http://qudt.org/vocab/unit/")
OBO = Namespace("http://purl.obolibrary.org/obo/")
IAO_DEFINITION = OBO.IAO_0000115

QUANTITY_KINDS = ["Wavelength", "Energy", "Transmittance", "TransmittanceDensity", "Count",
                  "Dimensionless"]
UNITS = ["NanoM", "MicroM", "M", "EV", "J", "PERCENT", "FRACTION", "UNITLESS", "NUM"]
CHMO_TERMS = ["CHMO_0000292",   # ultraviolet-visible spectrophotometry
              "CHMO_0000842",   # ultraviolet-visible spectrum
              "CHMO_0002804",   # blank value
              "CHMO_0001803"]   # ultraviolet-visible spectrometer

KEEP = {RDF.type, RDFS.label, DCTERMS.description, QUDT.plainTextDescription, QUDT.symbol,
        QUDT.conversionMultiplier, QUDT.hasQuantityKind, QUDT.latexDefinition, IAO_DEFINITION,
        RDFS.subClassOf}


def english_or_plain(obj) -> bool:
    return not isinstance(obj, Literal) or obj.language in (None, "en")


def copy_terms(src: Graph, dst: Graph, iris, linkable=()):
    kept_iris = set(iris) | set(linkable)
    for iri in iris:
        found = False
        for p, o in src.predicate_objects(iri):
            found = True
            if p not in KEEP or not english_or_plain(o):
                continue
            if p == QUDT.hasQuantityKind and o not in kept_iris:
                continue  # only keep links to quantity kinds that are in the excerpt
            if p == RDFS.subClassOf and not isinstance(o, URIRef):
                continue  # skip OWL restrictions
            if isinstance(o, Literal) and isinstance(o.value, str):
                o = Literal(" ".join(o.value.split()), lang=o.language, datatype=o.datatype)
            dst.add((iri, p, o))
        if not found:
            raise KeyError(f"{iri} not found in source")


def main(qk_path, unit_path, chmo_path, out_path):
    out = Graph()
    for prefix, ns in [("qudt", QUDT), ("quantitykind", QK), ("unit", UNIT), ("obo", OBO),
                       ("skos", SKOS), ("dcterms", DCTERMS)]:
        out.bind(prefix, ns)
    qk_iris = [QK[n] for n in QUANTITY_KINDS]
    unit_iris = [UNIT[n] for n in UNITS]

    g = Graph().parse(qk_path, format="turtle")
    copy_terms(g, out, qk_iris)
    g = Graph().parse(unit_path, format="turtle")
    copy_terms(g, out, unit_iris, linkable=qk_iris)
    g = Graph().parse(chmo_path, format="xml")
    copy_terms(g, out, [OBO[t] for t in CHMO_TERMS])

    header = ("# Excerpt of QUDT (quantity kinds and units) and CHMO terms used by the demo.\n"
              "# Generated by scripts/build_external_excerpt.py. Do not edit by hand.\n"
              "# QUDT: CC BY 4.0, attribution to QUDT.org. CHMO: CC BY 4.0, Royal Society of "
              "Chemistry.\n")
    Path(out_path).write_text(header + out.serialize(format="turtle"), encoding="utf-8")
    print(f"{len(out)} triples written to {out_path}")


if __name__ == "__main__":
    here = Path(__file__).resolve().parent.parent
    main(*sys.argv[1:4], here / "ontology" / "external_excerpt.ttl")
